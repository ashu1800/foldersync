const stored = localStorage.getItem("foldersync.lang");
const initial = stored === "en" || stored === "zh" ? stored : "zh";

void i18n.use(initReactI18next).init({
  resources: {
    zh: { translation: zh },
    en: { translation: en },
  },
  lng: initial,
  fallbackLng: "zh",
  interpolation: { escapeValue: false },
});

document.documentElement.lang = initial === "en" ? "en" : "zh-CN";

/** 切换语言并记住选择。 */
export function setLanguage(lang: "zh" | "en") {
  localStorage.setItem("foldersync.lang", lang);
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  void i18n.changeLanguage(lang);
}

export default i18n;
